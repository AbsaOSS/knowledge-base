/**
 * template.js — the headless document shell for single-page docs.
 *
 * Deliberately dependency-free: the knowledge base's own test fixture generator
 * (scripts/setup-test-apps.mjs) imports this module so the fixture and the real
 * action agree on the document shell without pulling the action's node_modules
 * into the knowledge base build.
 *
 * Everything emitted here must satisfy contract/HEADLESS_RULES.md:
 *   • data-kb-headless="true" on <html>
 *   • no <base> tag, all asset paths relative
 *   • no site-level <header>, no sidebar, no theme toggle
 *   • light only — no dark palette, no localStorage theme bootstrap
 */

