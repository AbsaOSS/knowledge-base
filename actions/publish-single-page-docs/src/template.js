// ── Mermaid bootstrap ─────────────────────────────────────────────────────────

/**
 * Init script for the vendored mermaid bundle.
 *
 * Vendored rather than loaded from a CDN: knowledge base pages are re-hosted inside
 * a web fragment behind a strict CSP, so every asset a doc needs must live in its
 * own artifact. `startOnLoad` is off because the knowledge base swaps pages with
 * Astro's ClientRouter — rendering is driven from both the initial load and the
 * `astro:page-load` event instead.
 *
 * Shipped as a FILE rather than inlined.
 *
 * It used to be an inline <script> in the document. That is the one thing that
 * makes a meaningful Content-Security-Policy impossible: allowing it means
 * `script-src 'unsafe-inline'`, which allows every injected script too, and
 * hashing it would hard-couple the knowledge base's nginx config to this action's
 * exact bytes — bundles published by an older version would then break. As a
 * file it is covered by `script-src 'self'` and nothing has to know about it.
 */
export const MERMAID_INIT_JS = `/* Generated by AbsaOSS/knowledge-base/actions/publish-single-page-docs — do not edit. */
(function () {
  var render = function () {
    if (!window.mermaid) return;
    var nodes = document.querySelectorAll('pre.mermaid:not([data-processed])');
    if (!nodes.length) return;
    window.mermaid.initialize({
      startOnLoad: false,
      theme: 'base',
      securityLevel: 'strict',
      fontFamily: 'Inter, Noto Sans, ui-sans-serif, system-ui, sans-serif',
      themeVariables: {
        primaryColor: '#f8eaee', primaryTextColor: '#1b0e12', primaryBorderColor: '#af144b',
        lineColor: '#93103f', secondaryColor: '#f0d0da', tertiaryColor: '#fdf8f9'
      }
    });
    try { window.mermaid.run({ nodes: nodes }); } catch (e) { /* leave the source visible */ }
  };
  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', render);
  else render();
  document.addEventListener('astro:page-load', render);
})();
`;

/** The two external <script> tags a mermaid-using doc needs. No inline script. */
export function mermaidBootstrap() {
  return `<script src="${MERMAID_PATH}"></script>
<script src="${MERMAID_INIT_PATH}"></script>`;
}

// ── Document ──────────────────────────────────────────────────────────────────

/**
 * Builds a complete headless HTML document for one doc.
 *
 * @param {object}  doc
 * @param {string}  doc.title        - human-readable page title
 * @param {string}  doc.description  - catalog description, also the meta description
 * @param {string}  doc.bodyHtml     - rendered markdown (already HTML)
 * @param {boolean} [doc.usesMermaid] - true when the body contains a mermaid block
 * @param {boolean} [doc.hasHeading]  - true when the body already opens with an <h1>
 * @returns {string}
 */
export function renderDocument({ title, description, bodyHtml, usesMermaid = false, hasHeading = true }) {
  // Only synthesise a lede when the author's markdown has no <h1> of its own —
  // duplicating the title above an existing heading reads as a bug.
  const lede = hasHeading ? '' : `  <header class="kb-doc-lede">
    <h1>${escapeHtml(title)}</h1>
    <p>${escapeHtml(description)}</p>
  </header>
`;

  return `<!DOCTYPE html>
<html lang="en" data-kb-headless="true">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${escapeHtml(title)}</title>
<meta name="description" content="${escapeHtml(description)}">
<link rel="stylesheet" href="${CSS_PATH}">
</head>
<body>
<article class="kb-doc">
${lede}${bodyHtml.trim()}
</article>
${usesMermaid ? mermaidBootstrap() + '\n' : ''}</body>
</html>
`;
}
